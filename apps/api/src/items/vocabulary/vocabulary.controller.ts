import {
  Body,
  Controller,
  Delete,
  Get,
  Header,
  HttpCode,
  HttpStatus,
  NotFoundException,
  Param,
  Patch,
  Post,
  StreamableFile,
  UseGuards,
} from '@nestjs/common';
import type { AuthUser } from '../../auth/auth-user.js';
import { CurrentUser } from '../../auth/current-user.decorator.js';
import { JwtAuthGuard } from '../../auth/guards/jwt-auth.guard.js';
import { PronunciationService } from '../../pronunciation/pronunciation.service.js';
import { ItemsService } from '../items.service.js';
import { CreateVocabularyDto } from './dto/create-vocabulary.dto.js';
import { UpdateVocabularyDto } from './dto/update-vocabulary.dto.js';
import { toVocabularyView } from './vocabulary-view.js';

@Controller('vocabulary')
@UseGuards(JwtAuthGuard)
export class VocabularyController {
  constructor(
    private readonly items: ItemsService,
    private readonly pronunciations: PronunciationService,
  ) {}

  /** Creates the word and its two cards (English → French, French → English). */
  @Post()
  async create(@CurrentUser() user: AuthUser, @Body() dto: CreateVocabularyDto) {
    const item = await this.items.create(user.id, 'Vocabulary', {
      word: dto.word,
      translation: dto.translation,
      example: dto.example ?? null,
    });
    this.pronunciations.request(item.id); // MEM-39, in the background
    return toVocabularyView(item);
  }

  @Get()
  async findAll(@CurrentUser() user: AuthUser) {
    return (await this.items.findAll(user.id, 'Vocabulary')).map(toVocabularyView);
  }

  @Get(':id')
  async findOne(@CurrentUser() user: AuthUser, @Param('id') id: string) {
    return toVocabularyView(await this.items.findOne(user.id, id, 'Vocabulary'));
  }

  /**
   * Changes the English, the French or the example (MEM-19). The cards, the
   * learning state and the review history stay as they are; an empty
   * example removes it.
   */
  @Patch(':id')
  async update(@CurrentUser() user: AuthUser, @Param('id') id: string, @Body() dto: UpdateVocabularyDto) {
    const changes = { ...dto, ...(dto.example !== undefined && { example: dto.example.trim() || null }) };
    const item = await this.items.update(user.id, id, 'Vocabulary', changes);
    if (dto.word !== undefined) this.pronunciations.request(id); // new English, new audio (MEM-39)
    return toVocabularyView(item);
  }

  /**
   * The audio of the English (MEM-39), generated by Kokoro: 404 while there
   * is none matching the current English (the web app then uses the
   * browser's speech synthesis). Deleting the item deletes it (cascade).
   */
  @Get(':id/pronunciation')
  @Header('Cache-Control', 'private, no-store')
  async pronunciation(@CurrentUser() user: AuthUser, @Param('id') id: string): Promise<StreamableFile> {
    const found = await this.pronunciations.find(user.id, id);
    if (!found) throw new NotFoundException('No pronunciation for this item');
    return new StreamableFile(found.audio, { type: found.mimeType, length: found.audio.length });
  }

  /** Deletes the item with its two cards and their history (MEM-20). */
  @Delete(':id')
  @HttpCode(HttpStatus.NO_CONTENT)
  remove(@CurrentUser() user: AuthUser, @Param('id') id: string) {
    return this.items.remove(user.id, id, 'Vocabulary');
  }
}
