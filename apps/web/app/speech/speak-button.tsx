'use client';

import { useEffect, useState, useSyncExternalStore } from 'react';
import { canPronounce, preloadPronunciation, pronounce, subscribeToVoices } from '../../lib/speech';

/**
 * Loads the audio of a card in advance (MEM-39), so that it starts at once,
 * including when it is read automatically on reveal (MEM-38). Returns
 * whether it is ready.
 */
export function usePronunciationAudio(audioUrl: string | undefined): boolean {
  const [ready, setReady] = useState<string | null>(null);
  useEffect(() => {
    if (!audioUrl) return;
    return preloadPronunciation(audioUrl, (state) => setReady(state === 'ready' ? audioUrl : null));
  }, [audioUrl]);
  return audioUrl !== undefined && ready === audioUrl;
}

/**
 * The loudspeaker button (MEM-37): reads the English text aloud, from the
 * start at each click. With `audioUrl`, the audio generated by Kokoro
 * (MEM-39), else the browser's voice. Hidden when neither is available.
 * Shortcut: P. Only one is shown at a time on a card. It doesn't stop the
 * reading when it disappears: the card does, when it changes
 * (lib/speech.ts, stopPronouncing).
 */
export function SpeakButton({ text, audioUrl }: { text: string; audioUrl?: string }) {
  // Unknown on the server (false); in the browser, follows the list of voices.
  const voice = useSyncExternalStore(subscribeToVoices, canPronounce, () => false);
  const audio = usePronunciationAudio(audioUrl);
  const available = voice || audio;

  useEffect(() => {
    if (!available) return;
    function onKeyDown(event: KeyboardEvent) {
      if (event.repeat || event.ctrlKey || event.metaKey || event.altKey) return;
      const target = event.target as HTMLElement | null;
      if (target?.closest('input, textarea, select, [contenteditable="true"]')) return;
      if (event.key === 'p' || event.key === 'P') {
        event.preventDefault();
        pronounce(text, audioUrl);
      }
    }
    window.addEventListener('keydown', onKeyDown);
    return () => window.removeEventListener('keydown', onKeyDown);
  }, [available, text, audioUrl]);

  if (!available) return null;
  return (
    <button
      type="button"
      className="speak-button"
      aria-label="Écouter la prononciation"
      title="Écouter la prononciation (P)"
      onClick={() => pronounce(text, audioUrl)}
    >
      <svg viewBox="0 0 24 24" width="20" height="20" aria-hidden="true">
        <path
          d="M4 9.5h3.5L12 5.5v13l-4.5-4H4z"
          fill="currentColor"
          stroke="currentColor"
          strokeWidth="1.4"
          strokeLinejoin="round"
        />
        <path
          d="M15.5 9a4 4 0 0 1 0 6M18 6.5a7.5 7.5 0 0 1 0 11"
          fill="none"
          stroke="currentColor"
          strokeWidth="1.7"
          strokeLinecap="round"
        />
      </svg>
    </button>
  );
}

/** A line of English with its loudspeaker button on the right; `actions`: other buttons next to it (MEM-91). */
export function Speakable({
  text,
  audioUrl,
  actions,
  children,
}: {
  text: string;
  audioUrl?: string;
  actions?: React.ReactNode;
  children: React.ReactNode;
}) {
  return (
    <div className="speakable">
      {children}
      <SpeakButton text={text} audioUrl={audioUrl} />
      {actions}
    </div>
  );
}
