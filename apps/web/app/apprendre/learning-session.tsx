'use client';

import Link from 'next/link';
import { useEffect, useState } from 'react';
import { formatDelay } from '../../lib/format';
import { pronounce, stopPronouncing } from '../../lib/speech';
import type { LearningItem, LearningSession } from '../../lib/types';
import { pronunciationUrl } from '../../lib/pronunciation-url';
import { Speakable, usePronunciationAudio } from '../speech/speak-button';
import { type Answer, answerOfKey, RatingButtons } from '../review/rating-buttons';
import { ListeningStep } from './listening-step';
import { sendAnswers } from './send-answers';

type Phase = 'discover' | 'rate' | 'done';

interface LearningSessionViewProps {
  session: LearningSession;
  /** The server's clock, so that the server and the browser show the same delays. */
  now: string;
  /** The delays under the rating buttons: a setting, off by default (MEM-49). */
  showDelays: boolean;
  /** MEM-91: the pronunciation assessment is configured on the server (« Répéter »). */
  canAssess?: boolean;
}

/**
 * A learning session (MEM-21), in two steps over the same items:
 * 1. « Écoute et prononciation » (MEM-101, MEM-102): one item after the
 *    other, its English read at once, with its translation, « Réécouter »
 *    and « Évaluer ma prononciation »; no rating, no state changed;
 * 2. as in the review: the French → English card, rated with the four
 *    buttons. That rating moves the item to "En cours d'apprentissage";
 *    « Appris » straight to "Appris", out of the review (MEM-46).
 * Same shortcuts as the review: Space goes on in step 1, reveals in step 2, 1-4 answer (4: « Appris »).
 * MEM-47: as in the review, an item rated « À revoir » at step 2 is put back
 * at the bottom of the pile, until it gets another answer.
 * The answers of step 2 are kept here and only sent at the end of the
 * session, in their order (the first one moves the item to "En cours
 * d'apprentissage", the next ones are reviews of its card): leaving the
 * session ("Arrêter", another page) keeps every item "À apprendre".
 */
export function LearningSessionView({ session, now, showDelays, canAssess = false }: LearningSessionViewProps) {
  const [items] = useState(session.items);
  const [phase, setPhase] = useState<Phase>('discover');
  const [pile, setPile] = useState<number[]>([]); // step 2: indexes in `items`, the current one first
  const [answers, setAnswers] = useState<Record<string, Answer[]>>({}); // step 2, sent at the end
  const [clock, setClock] = useState(now);
  const [revealed, setRevealed] = useState(false);
  const [learned, setLearned] = useState<LearningItem[]>([]); // now in the review
  const [known, setKnown] = useState<LearningItem[]>([]); // « Appris »: out of the review
  const [failed, setFailed] = useState(0);
  const [sending, setSending] = useState(false); // the answers, at the end of the session

  const item = phase === 'rate' ? items[pile[0]] : undefined;
  // Its audio generated by Kokoro (MEM-39), loaded in advance: at step 2,
  // read at once on reveal (MEM-38).
  const audioUrl = item ? pronunciationUrl(item.id, item.word) : undefined;
  usePronunciationAudio(audioUrl);

  // Leaving the session stops the reading (MEM-37).
  useEffect(() => stopPronouncing, []);

  // MEM-38: at step 2 the answer is the English, read as it appears. Called
  // in the click or key handler: browsers only allow speech started by the user.
  function reveal() {
    setRevealed(true);
    if (item) pronounce(item.word, audioUrl);
  }

  /** End of step 1: the whole series, in its order, at step 2. */
  function evaluate() {
    setPhase('rate');
    setPile(items.map((_, i) => i));
  }

  function rate(answer: Answer) {
    if (!item || sending) return;
    stopPronouncing();
    const all = { ...answers, [item.id]: [...(answers[item.id] ?? []), answer] };
    const rest = answer === 'Again' ? [...pile.slice(1), pile[0]] : pile.slice(1);
    setAnswers(all);
    setClock(new Date().toISOString());
    setRevealed(false);
    setPile(rest);
    if (rest.length === 0) void save(all);
  }

  /** End of the session: the answers of each item, in their order. */
  async function save(all: Record<string, Answer[]>) {
    setSending(true);
    for (const it of items) {
      const outcome = await sendAnswers(it.id, it.cardId, all[it.id] ?? []);
      if (outcome === 'failed') setFailed((count) => count + 1);
      else if (outcome === 'learned') setKnown((done) => [...done, it]);
      else if (outcome === 'learning') setLearned((done) => [...done, it]);
    }
    setSending(false);
    setPhase('done');
  }

  // Keyboard, at step 2: Space (or Enter) reveals, 1-4 answer.
  useEffect(() => {
    function onKeyDown(event: KeyboardEvent) {
      // Step 1 has its own shortcuts (listening-step.tsx).
      if (event.repeat || event.ctrlKey || event.metaKey || event.altKey || phase !== 'rate') return;
      if (event.key === ' ' || event.key === 'Enter') {
        // Let a focused button handle Enter/Space itself, once.
        if (event.target instanceof HTMLButtonElement || event.target instanceof HTMLAnchorElement) return;
        event.preventDefault();
        if (!revealed) reveal();
      } else if (revealed) {
        const answer = answerOfKey(event.key, true);
        if (answer) rate(answer);
      }
    }
    window.addEventListener('keydown', onKeyDown);
    return () => window.removeEventListener('keydown', onKeyDown);
  });

  if (phase === 'done') {
    const remaining = session.total - learned.length - known.length;
    return (
      <section className="learning-done">
        <h2>Session terminée</h2>
        <p>
          {learned.length + known.length === 0 && 'Aucun élément n’a pu être enregistré.'}
          {learned.length > 0 &&
            `${learned.length}\u00a0élément${learned.length > 1 ? 's' : ''} passe${learned.length > 1 ? 'nt' : ''} en apprentissage : ${learned.length > 1 ? 'ils entrent' : 'il entre'} en révision.`}
          {learned.length > 0 && known.length > 0 && ' '}
          {known.length > 0 &&
            `${known.length}\u00a0élément${known.length > 1 ? 's' : ''} déjà connu${known.length > 1 ? 's' : ''} : ${known.length > 1 ? 'ils passent' : 'il passe'} directement à « Appris », sans révision.`}
          {failed > 0 && ` ${failed} n’a pas pu être enregistré (déjà appris ou supprimé entre-temps).`}
        </p>
        <ul className="learning-done__list">
          {learned.map((done) => (
            <li key={done.id}>
              <strong lang="en">{done.word}</strong> → {done.translation}
            </li>
          ))}
          {known.map((done) => (
            <li key={done.id}>
              <strong lang="en">{done.word}</strong> → {done.translation}{' '}
              <span className="learning-done__known">· Appris</span>
            </li>
          ))}
        </ul>
        <p className="learning-done__links">
          <Link href="/anglais" className="space__review">
            Retour à l’anglais
          </Link>
          {remaining > 0 && (
            // MEM-94: the next session is prepared too.
            <a href="/anglais/preparer" className="learning-done__next">
              Apprendre les suivants ({remaining})
            </a>
          )}
        </p>
      </section>
    );
  }

  if (phase === 'discover') {
    return <ListeningStep items={items} canAssess={canAssess} onDone={evaluate} />;
  }

  if (!item) {
    // Step 2 over: the answers are being sent.
    return (
      <p className="review-progress" role="status">
        Enregistrement de la session…
      </p>
    );
  }

  // The items answered so far (« À revoir » put back in the pile does not count).
  const position = items.length - pile.length;
  const due = answers[item.id]?.length ? item.nextDueAfterAgain : item.nextDue; // put back after « À revoir »

  return (
    <section aria-label="Apprentissage">
      <p className="review-progress">
        <strong>Étape 2 · Français → anglais</strong> · {position + 1} / {items.length} ·{' '}
        <Link href="/anglais">Arrêter</Link>
      </p>
      <ol className="learning-steps" aria-hidden="true">
        {items.map((it, i) => (
          <li key={it.id} className={it === item ? 'is-current' : !pile.includes(i) ? 'is-done' : undefined} />
        ))}
      </ol>

      <article className="review-card">
        <p className="review-card__author">Français → anglais</p>
        {revealed ? (
          <>
            <p className="review-card__recall">{item.translation}</p>
            <Speakable text={item.word} audioUrl={audioUrl}>
              <blockquote className="review-card__text" lang="en">
                {item.word}
              </blockquote>
            </Speakable>
            <Examples item={item} />
            <RatingButtons
              onAnswer={rate}
              withLearned
              delays={
                showDelays
                  ? Object.fromEntries(
                      (['Again', 'Hard', 'Good'] as const).map((rating) => [
                        rating,
                        formatDelay(new Date(clock), new Date(due[rating])),
                      ]),
                    )
                  : undefined
              }
              disabled={sending}
            />
          </>
        ) : (
          <>
            <blockquote className="review-card__text review-card__text--cue">{item.translation}</blockquote>
            <p className="review-card__question">Comment le dit-on en anglais ?</p>
            <button type="button" className="review-card__reveal" onClick={reveal}>
              Afficher la réponse <kbd>Espace</kbd>
            </button>
          </>
        )}
      </article>
    </section>
  );
}

/** The example sentences of the back of a card: the English, then the French (MEM-42). */
function Examples({ item }: { item: LearningItem }) {
  return (
    <>
      {item.example && (
        <p className="review-card__note" lang="en">
          {item.example}
        </p>
      )}
      {item.frenchExample && (
        <p className="review-card__note review-card__note--fr" lang="fr">
          {item.frenchExample}
        </p>
      )}
    </>
  );
}
