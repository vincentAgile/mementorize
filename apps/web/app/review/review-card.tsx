'use client';

import { type ReactNode, useCallback, useEffect, useRef, useState, useTransition } from 'react';
import { pronounce, stopPronouncing } from '../../lib/speech';
import { PronunciationFrame, PronunciationFramePlaceholder } from '../apprendre/pronunciation-practice';
import { Speakable, usePronunciationAudio } from '../speech/speak-button';
import { type Answer, answerOfKey, RatingButtons } from './rating-buttons';

/** One side of a card: built by the page, depending on the card's kind. */
export interface CardFace {
  heading?: string; // "Socrates", "Anglais → français"; none: no heading line (MEM-100)
  subheading?: string | null; // source of a quote
  main: string; // the cue (front) or the answer (back)
  figure?: ReactNode; // shown instead of `main` (mind maps), rendered by the page
  lang?: string; // lang attribute of `main`, for screen readers and hyphenation
  note?: string | null; // back only: example sentence (English, for vocabulary)
  frenchNote?: string | null; // back only: its French version (MEM-42)
  prompt?: string; // front only: what to do
  speak?: boolean; // `main` is English vocabulary: a loudspeaker button next to it (MEM-37)
  audioUrl?: string; // with `speak`: its audio generated by Kokoro (MEM-39)
  assessItemId?: string; // with `speak`: offers « Évaluer ma prononciation » for this item (back only)
}

interface ReviewCardProps {
  front: CardFace;
  back: CardFace;
  /** Keep the question visible above the answer (vocabulary: word -> translation). */
  repeatFront?: boolean;
  /** When the card comes back with each rating ("10 min"); none when the setting is off (MEM-49). */
  delays?: Partial<Record<Answer, string>>;
  /** Offer the button "Appris" (MEM-22, MEM-48). */
  withLearned: boolean;
  /** Sends the answer; the session then shows the next card. */
  onAnswer: (answer: Answer) => Promise<void>;
}

export function ReviewCard({ front, back, repeatFront = false, delays, withLearned, onAnswer }: ReviewCardProps) {
  const [revealed, setRevealed] = useState(false);
  // While an answer is being sent: buttons disabled.
  const [pending, startTransition] = useTransition();
  // Set as soon as an answer is sent. `disabled={pending}` isn't enough on
  // its own: two clicks or key presses within the same frame both get
  // through before React re-renders, and the card would be rated twice.
  // The component is remounted for the next card (see `key` in
  // review-session.tsx), which resets it.
  const answered = useRef(false);

  const answer = useCallback(
    (choice: Answer) => {
      if (answered.current || (choice === 'Learned' && !withLearned)) return;
      answered.current = true;
      stopPronouncing();
      startTransition(() => onAnswer(choice));
    },
    [withLearned, onAnswer],
  );

  // A new card mounts a new component: the reading of the previous one stops (MEM-37).
  useEffect(() => stopPronouncing, []);

  // MEM-38: when the answer is English (French → English), it is read as it
  // appears. Called in the click or key handler: browsers only allow speech
  // started by the user. Without speech synthesis, nothing is said.
  const reveal = useCallback(() => {
    setRevealed(true);
    if (back.speak) pronounce(back.main, back.audioUrl);
  }, [back.speak, back.main, back.audioUrl]);

  // The English of the answer is loaded in advance: read at once on reveal (MEM-38, MEM-39).
  usePronunciationAudio(back.speak ? back.audioUrl : undefined);

  // Keyboard shortcuts: space reveals the answer, 1-3 pick a rating, 4 "Appris" (MEM-46).
  useEffect(() => {
    function onKeyDown(event: KeyboardEvent) {
      // Held key (auto-repeat) or browser shortcut such as Ctrl+1: ignored.
      if (event.repeat || event.ctrlKey || event.metaKey || event.altKey) return;
      if (!revealed && (event.key === ' ' || event.key === 'Enter')) {
        // A focused button (the loudspeaker, MEM-37) handles Enter/Space itself.
        if (event.target instanceof HTMLButtonElement || event.target instanceof HTMLAnchorElement) return;
        event.preventDefault();
        reveal();
      } else if (revealed) {
        const choice = answerOfKey(event.key, withLearned);
        if (choice) answer(choice);
      }
    }
    window.addEventListener('keydown', onKeyDown);
    return () => window.removeEventListener('keydown', onKeyDown);
  }, [revealed, reveal, answer, withLearned]);

  const face = revealed ? back : front;
  const assessItemId = back.speak ? back.assessItemId : undefined;

  // Both sides take the same place, one over the other: the hidden one only
  // keeps its room (no button, no shortcut). « Afficher la réponse » is thus
  // where the rating buttons will be, and revealing moves nothing (MEM-100).
  // A mind map is not doubled: its two sides already have the same size.
  const stacked = !front.figure && !back.figure;
  const backBody = (ghost: boolean) => (
    <div
      className={
        assessItemId
          ? 'review-card__body review-card__body--with-practice review-card__body--assess'
          : 'review-card__body'
      }
    >
      <div className="review-card__body-main">
        {/* The French and the English: on a phone, a fixed room; the examples under it, as long as they are (MEM-100) */}
        <div className="review-card__terms">
          {repeatFront && (
            <Line face={front} ghost={ghost}>
              <p className="review-card__recall" lang={front.lang}>
                {front.main}
              </p>
            </Line>
          )}
          {back.figure ?? (
            <Line face={back} ghost={ghost}>
              <blockquote className="review-card__text" lang={back.lang}>
                {back.main}
              </blockquote>
            </Line>
          )}
        </div>
        {back.note && (
          <p className="review-card__note" lang="en">
            {back.note}
          </p>
        )}
        {back.frenchNote && (
          <p className="review-card__note review-card__note--fr" lang="fr">
            {back.frenchNote}
          </p>
        )}
      </div>
      {assessItemId &&
        (ghost ? <PronunciationFramePlaceholder /> : <PronunciationFrame key={assessItemId} itemId={assessItemId} />)}
    </div>
  );
  const frontBody = (ghost: boolean) => (
    <>
      {front.figure ?? (
        <Line face={front} ghost={ghost}>
          <blockquote className="review-card__text review-card__text--cue" lang={front.lang}>
            {front.main}
          </blockquote>
        </Line>
      )}
      {front.prompt && <p className="review-card__question">{front.prompt}</p>}
    </>
  );

  return (
    <article className={`review-card${assessItemId ? ' review-card--wide' : ''}`}>
      {face.heading && (
        <p className="review-card__author">
          {face.heading}
          {face.subheading && <span className="review-card__source"> · {face.subheading}</span>}
        </p>
      )}

      <div className={stacked ? 'review-card__faces' : undefined}>
        <div className="review-card__face">{revealed ? backBody(false) : frontBody(false)}</div>
        {stacked && (
          <div className="review-card__face review-card__face--ghost" aria-hidden="true" inert>
            {revealed ? frontBody(true) : backBody(true)}
          </div>
        )}
      </div>

      {revealed ? (
        <RatingButtons onAnswer={answer} withLearned={withLearned} delays={delays} disabled={pending} />
      ) : (
        // MEM-100: « Afficher la réponse » takes exactly the room of the rating
        // buttons: it lies over an invisible copy of them, so the question and
        // the answer have the same height whatever the fonts of the system.
        <div className="review-card__reveal-row">
          <div className="review-card__reveal-room" aria-hidden="true" inert>
            <RatingButtons onAnswer={() => undefined} withLearned={withLearned} delays={delays} />
          </div>
          <button type="button" className="review-card__reveal review-card__reveal--wide" onClick={reveal}>
            Afficher la réponse <kbd>Espace</kbd>
          </button>
        </div>
      )}
    </article>
  );
}

/**
 * The text of a face, with the loudspeaker button when it is English
 * vocabulary (MEM-37). `ghost`: the hidden side, the button's room only.
 */
function Line({ face, ghost = false, children }: { face: CardFace; ghost?: boolean; children: ReactNode }) {
  if (!face.speak) return children;
  if (ghost) {
    return (
      <div className="speakable">
        {children}
        <span className="speak-button" />
      </div>
    );
  }
  return (
    <Speakable text={face.main} audioUrl={face.audioUrl}>
      {children}
    </Speakable>
  );
}
